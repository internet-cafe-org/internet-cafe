"""Happy path tests for key generation script and artifacts (SEC-00)."""

from pathlib import Path
from app.jwt import create_access_token, verify_access_token
from tools.generate_keys import (
    generate_all_keys,
    generate_blind_index_key,
    generate_data_enc_keys,
    generate_es256_keypair,
)


def test_generate_es256_keypair():
    """Verify generated ES256 keypair produces valid PEM headers."""
    priv_pem, pub_pem = generate_es256_keypair()

    assert priv_pem.strip().endswith("-----END " + "PRIVATE KEY-----")
    assert priv_pem.startswith("-----BEGIN " + "PRIVATE KEY-----")
    assert pub_pem.strip().endswith("-----END PUBLIC KEY-----")


def test_generate_data_enc_keys():
    """Verify generated data encryption ring format."""
    ring = generate_data_enc_keys("1")

    assert "1" in ring
    assert isinstance(ring["1"], str)
    assert len(ring["1"]) == 64  # 32 bytes in hex
    bytes.fromhex(ring["1"])  # Validates hex decode


def test_generate_blind_index_key():
    """Verify generated blind index key format."""
    key = generate_blind_index_key()

    assert isinstance(key, str)
    assert len(key) == 64  # 32 bytes in hex
    bytes.fromhex(key)  # Validates hex decode


def test_generate_all_keys_integration(tmp_path: Path):
    """Verify full key generation pipeline and end-to-end token signing/verification."""
    results = generate_all_keys(tmp_path)

    priv_path = Path(results["jwt_private_key"])
    pub_path = Path(results["jwt_public_key"])
    enc_path = Path(results["data_enc_keys"])
    bidx_path = Path(results["blind_index_key"])
    env_path = Path(results["env_snippet"])

    assert priv_path.exists()
    assert pub_path.exists()
    assert enc_path.exists()
    assert bidx_path.exists()
    assert env_path.exists()

    # Verify keys generated by tool work immediately with JWT module
    token = create_access_token(
        subject="e2e-test-subject",
        role="student",
        private_key=str(priv_path),
    )
    claims = verify_access_token(token, public_key=str(pub_path))
    assert claims["sub"] == "e2e-test-subject"
    assert claims["role"] == "student"
